-- Учебный проект, схема для Spring Boot 3.3.5 / Hibernate 6, PostgreSQL.
-- На уже существующей базе проверить совпадение структуры до применения.
BEGIN;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(255) NOT NULL,
 email VARCHAR(255) NOT NULL UNIQUE,
 CONSTRAINT ck_users_name_nonblank CHECK (length(btrim(name)) > 0),
 CONSTRAINT ck_users_email_nonblank CHECK (length(btrim(email)) > 0)
);
CREATE TABLE IF NOT EXISTS exams (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(255) NOT NULL,
 passing_score INTEGER NOT NULL,
 time_limit INTEGER NOT NULL,
 status VARCHAR(255) NOT NULL,
 CONSTRAINT ck_exam_title_nonblank CHECK (length(btrim(title)) > 0),
 CONSTRAINT ck_exam_score CHECK (passing_score >= 0),
 CONSTRAINT ck_exam_time CHECK (time_limit > 0),
 CONSTRAINT ck_exam_status CHECK (status IN ('DRAFT','ACTIVE'))
);
CREATE TABLE IF NOT EXISTS exam_tasks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 exam_id BIGINT NOT NULL REFERENCES exams(id),
 description TEXT NOT NULL,
 reference_answer VARCHAR(255) NOT NULL,
 max_score INTEGER NOT NULL,
 CONSTRAINT ck_task_description CHECK (length(btrim(description)) > 0),
 CONSTRAINT ck_task_answer CHECK (length(btrim(reference_answer)) > 0),
 CONSTRAINT ck_task_score CHECK (max_score >= 0)
);
CREATE TABLE IF NOT EXISTS exam_attempts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 exam_id BIGINT NOT NULL REFERENCES exams(id),
 user_id BIGINT NOT NULL REFERENCES users(id),
 start_time TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
 end_time TIMESTAMP(6) WITHOUT TIME ZONE,
 final_score INTEGER,
 status VARCHAR(255) NOT NULL,
 CONSTRAINT ck_attempt_status CHECK (status IN ('IN_PROGRESS','PASSED','FAILED')),
 CONSTRAINT ck_attempt_score CHECK (final_score IS NULL OR final_score >= 0),
 CONSTRAINT ck_attempt_times CHECK (end_time IS NULL OR end_time >= start_time)
);
CREATE TABLE IF NOT EXISTS task_solutions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 attempt_id BIGINT NOT NULL REFERENCES exam_attempts(id),
 task_id BIGINT NOT NULL REFERENCES exam_tasks(id),
 student_answer VARCHAR(255) NOT NULL,
 score INTEGER NOT NULL,
 CONSTRAINT uk_solution_attempt_task UNIQUE (attempt_id,task_id),
 CONSTRAINT ck_solution_score CHECK (score >= 0),
 CONSTRAINT ck_solution_answer CHECK (length(btrim(student_answer)) > 0)
);
-- Для одновременно активных попыток одного пользователя допускается только одна запись.
-- Перед применением на старой БД завершите/очистите дубликаты IN_PROGRESS.
CREATE UNIQUE INDEX IF NOT EXISTS ux_active_attempt_per_user
 ON exam_attempts(user_id) WHERE status = 'IN_PROGRESS';
CREATE INDEX IF NOT EXISTS ix_exam_tasks_exam_id ON exam_tasks(exam_id);
CREATE INDEX IF NOT EXISTS ix_exam_attempts_exam_id ON exam_attempts(exam_id);
CREATE INDEX IF NOT EXISTS ix_exam_attempts_user_id ON exam_attempts(user_id);
CREATE INDEX IF NOT EXISTS ix_task_solutions_task_id ON task_solutions(task_id);
-- PostgreSQL 15+ по умолчанию ограничивает CREATE в public; закрепляем явно.
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO exam_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE users, exams, exam_tasks, exam_attempts, task_solutions TO exam_app;
GRANT USAGE, SELECT ON SEQUENCE users_id_seq, exams_id_seq, exam_tasks_id_seq, exam_attempts_id_seq, task_solutions_id_seq TO exam_app;
-- НЕ выдаём CREATE, ALTER, DROP, TRUNCATE, SUPERUSER, CREATEROLE.
COMMIT;
